package com.termux.app;

import android.content.Context;

import androidx.annotation.NonNull;

import com.termux.shared.android.PackageUtils;
import com.termux.shared.markdown.MarkdownUtils;
import com.termux.shared.termux.TermuxConstants;

/**
 * The links of the fork, which are shown in the about dialog and in the report of an issue.
 *
 * The app is a fork of Termux, so its repository, its releases and its issue tracker are not the ones of the
 * upstream app, and a user who is sent to the upstream tracker cannot be helped there.
 */
public final class ForkInfo {

    /** The repository of the fork. */
    public static final String REPOSITORY_URL = "https://github.com/clevebitr/termux-app";
    /** The issue tracker of the fork, which opens the form for a new issue. */
    public static final String ISSUES_URL = REPOSITORY_URL + "/issues/new";
    /** The release that the ci of the fork updates with every build. */
    public static final String LATEST_RELEASE_URL = REPOSITORY_URL + "/releases/tag/fork-latest";
    /** The page with all the releases of the fork. */
    public static final String RELEASES_URL = REPOSITORY_URL + "/releases";
    /** The features of the fork, in the repository. */
    public static final String FEATURES_DOC_URL = REPOSITORY_URL + "/blob/master/FORK.md";
    /** How the fork is built and signed, in the repository. */
    public static final String BUILD_DOC_URL = REPOSITORY_URL + "/blob/master/FORK_BUILD.md";
    /** The summary of the features that is included in the release notes of every build. */
    public static final String RELEASE_NOTES_DOC_URL = REPOSITORY_URL + "/blob/master/docs/FORK_RELEASE_NOTES.md";

    private ForkInfo() {
    }

    /**
     * @return The markdown block for the about dialog, which says which build this is and where to get the
     *         newer ones, instead of the links of the upstream app.
     */
    @NonNull
    public static String getBuildMarkdownString(@NonNull Context context) {
        String versionName = PackageUtils.getVersionNameForPackage(context);
        Integer versionCodeValue = PackageUtils.getVersionCodeForPackage(context);
        String versionCode = versionCodeValue != null ? String.valueOf(versionCodeValue) : "?";

        StringBuilder markdownString = new StringBuilder();
        markdownString.append("## This Build");
        markdownString.append("\n\n").append("- ").append(TermuxConstants.TERMUX_APP_NAME)
            .append(" fork, version ").append(versionName).append(" (").append(versionCode).append(")");
        markdownString.append("\n").append("- ").append(MarkdownUtils.getLinkMarkdownString(
            "Latest build", LATEST_RELEASE_URL));
        markdownString.append("\n").append("- ").append(MarkdownUtils.getLinkMarkdownString(
            "All releases", RELEASES_URL));
        markdownString.append("\n\n### Documentation");
        markdownString.append("\n").append(MarkdownUtils.getLinkMarkdownString(
            "Features of the fork", FEATURES_DOC_URL));
        markdownString.append("\n").append(MarkdownUtils.getLinkMarkdownString(
            "Release notes", RELEASE_NOTES_DOC_URL));
        markdownString.append("\n").append(MarkdownUtils.getLinkMarkdownString(
            "Building and signing", BUILD_DOC_URL));
        markdownString.append("\n##\n");

        return markdownString.toString();
    }

    /**
     * @return The markdown block for the end of a report, which says where the issue has to be reported.
     *
     * The report of a crash or of a command is generated by the app and copied by the user, so it has to say
     * that the upstream tracker is the wrong place for it.
     */
    @NonNull
    public static String getReportIssueMarkdownString() {
        StringBuilder markdownString = new StringBuilder();
        markdownString.append("## Where To Report An Issue");
        markdownString.append("\n\nThis is a fork of ").append(TermuxConstants.TERMUX_APP_NAME)
            .append(", so please report the issue to the tracker of the fork, not to the one of the upstream app:");
        markdownString.append("\n\n").append(MarkdownUtils.getLinkMarkdownString("New issue", ISSUES_URL));
        markdownString.append("\n\nPlease include the output of `termux-info` and, if the app crashed, the stack trace");
        markdownString.append("\nfrom `logcat`, since an issue without them usually cannot be reproduced.");
        markdownString.append("\n##\n");

        return markdownString.toString();
    }
}
